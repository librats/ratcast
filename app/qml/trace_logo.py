#!/usr/bin/env python3
"""The logo's drawing for RatLogo.qml, traced from docs/logo-dark.png.

Each part the start screen moves on its own (the signal's arcs, the rat, its
eye and whiskers, the screen, the camera's lens, the play button, the viewers
and their orbit) is a shape of its own in the picture: found by what it touches,
traced into SVG path data by potrace, and written to logo.js with the points
the animation turns or scales them about. Run it again when the logo changes:

    pip install potracer scipy pillow
    python app/qml/trace_logo.py
"""

import json
import pathlib

import numpy as np
import potrace
from PIL import Image
from scipy import ndimage

ROOT = pathlib.Path(__file__).resolve().parents[2]
# The drawing's origin and size in the picture.
OX, OY, W, H = 250, 125, 1062, 768

shape = np.array(Image.open(ROOT / "docs/logo-dark.png"))[..., 3] > 127
labels, _ = ndimage.label(shape)


def part(x, y):
    """The shape under a point of the picture."""
    label = labels[y, x]
    assert label, (x, y)
    return labels == label


parts = {
    "wifiOuter": part(786, 148),
    "wifiMiddle": part(754, 206),
    "wifiInner": part(765, 260),
    "monitor": part(1048, 334),
    "rat": part(587, 652),
    "lens": part(999, 344),
    "ringBack": part(358, 511),
    "whisker1": part(963, 486),
    "whisker2": part(975, 501),
    "play": part(1068, 554),
    "whisker3": part(958, 519),
    "avatarLeft": part(279, 592),
    "ringFront": part(516, 749),
    "avatarRight": part(1212, 706),
    "avatarBottom": part(739, 748),
    "ringRight": part(890, 780),
}
# The orbit's end on the right is one shape with the screen: apart from it.
rows, columns = np.indices(shape.shape)
end = (columns >= 1242) & (rows >= 575)
parts["ringEnd"] = parts["monitor"] & end
parts["monitor"] = parts["monitor"] & ~end
# The eye: the hole in the rat's head.
holes, _ = ndimage.label(ndimage.binary_fill_holes(parts["rat"]) & ~parts["rat"])
parts["eye"] = holes == holes[473, 848]
for name, mask in parts.items():
    assert mask.sum() > 150, name


def number(value):
    text = f"{value:.1f}"
    return text[:-2] if text.endswith(".0") else text


def trace(mask):
    ys, xs = np.nonzero(mask)
    x0, y0 = xs.min() - 3, ys.min() - 3
    region = mask[y0 : ys.max() + 4, x0 : xs.max() + 4]
    # potrace traces what is dark: the shape's complement handed over.
    path = potrace.Bitmap(~region).trace(turdsize=4, alphamax=1.0, opttolerance=0.2)

    def point(p):
        return f"{number(p.x + x0 - OX)} {number(p.y + y0 - OY)}"

    data = []
    for curve in path:
        data.append("M" + point(curve.start_point))
        for segment in curve:
            if segment.is_corner:
                data.append(f"L{point(segment.c)}L{point(segment.end_point)}")
            else:
                data.append(f"C{point(segment.c1)} {point(segment.c2)} {point(segment.end_point)}")
        data.append("Z")
    return "".join(data)


def box(mask):
    ys, xs = np.nonzero(mask)
    return [int(xs.min()) - OX, int(ys.min()) - OY, int(xs.max()) + 1 - OX, int(ys.max()) + 1 - OY]


lines = [
    "// Generated by trace_logo.py from docs/logo-dark.png: do not edit.",
    ".pragma library",
    "",
    f"var width = {W}",
    f"var height = {H}",
    "",
]
for name, mask in parts.items():
    lines.append(f"var {name} = {json.dumps(trace(mask))}")
    lines.append(f"var {name}Box = {json.dumps(box(mask))}")
(pathlib.Path(__file__).parent / "logo.js").write_text("\n".join(lines) + "\n", newline="\n")
